const charset = [...new Set(STRINGS.join("") + SAMPLES.join(""))].filter((c) => c !== "\n").join("");
if (charset.includes('"') || charset.includes("\\")) process.exit(2);

mkdirSync(MAIN, { recursive: true });
writeFileSync(resolve(MAIN, "pwcard_strings.h"), [
  "// GENERATED by tools/pwcard/gen_assets.mjs - do not edit.",
  "// Also the glyph-audit source for pw_font_22.c.",
  "#pragma once",
  "",
  ...STRINGS.map(([name, text]) => `#define ${name} ${JSON.stringify(text)}`),
  "",
].join("\n"));

const r = spawnSync(process.execPath, [
  lvfc, "--size", "22", "--bpp", "4", "--no-compress",
  "--format", "lvgl", "--font", ttf,
  "--symbols", charset,
  "--lv-font-name", "pw_font_22",
  "--lv-include", "lvgl.h",
  "-o", resolve(MAIN, "pw_font_22.c"),
]);
if (r.status !== 0) {
  console.error(r.stdout ? r.stdout.toString() : "", r.stderr ? r.stderr.toString() : "");
  process.exit(r.status ?? 1);
}
const fontC = readFileSync(resolve(MAIN, "pw_font_22.c"), "utf8");
const missing = [...charset].filter((c) => !fontC.includes(`"${c}"`) && c !== " " && !fontC.includes(c));
if (missing.length) {
  console.error("glyph audit FAILED, missing:", missing.join(" "));
  process.exit(3);
}

const ALPHABET = "abcdefghjkmnpqrstuvwxyzABCDEFGHJKLMNPQRSTUVWXYZ23456789";
const SEED = [0x50, 0x57, 0x43, 0x41, 0x52, 0x44, 0x00, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00];
const u32 = (b, i) => (b[i] | (b[i + 1] << 8) | (b[i + 2] << 16) | (b[i + 3] << 24)) >>> 0;
let s = [u32(SEED, 0), u32(SEED, 4), u32(SEED, 8), u32(SEED, 12)];
const rotl = (x, k) => ((x << k) | (x >>> (32 - k))) >>> 0;
const next = () => {
  const result = Math.imul(rotl(Math.imul(s[1], 5) >>> 0, 7) >>> 0, 9) >>> 0;
  const t = (s[1] << 17) >>> 0;
  s[2] = (s[2] ^ s[0]) >>> 0;
  s[3] = (s[3] ^ s[1]) >>> 0;
  s[1] = (s[1] ^ s[2]) >>> 0;
  s[0] = (s[0] ^ s[3]) >>> 0;
  s[2] = (s[2] ^ t) >>> 0;
  s[3] = rotl(s[3], 45);
  return result;
};
const ROWS = 8, COLS = 10;
const card = [];
for (let y = 0; y < ROWS; y++) {
  let row = "";
  for (let x = 0; x < COLS; x++) row += ALPHABET[next() % ALPHABET.length];
  card.push(row);
}
writeFileSync(resolve(MAIN, "pwcard_card.h"), [
  "// GENERATED by tools/pwcard/gen_assets.mjs - do not edit.",
  "#pragma once",
  "",
  `#define PWCARD_ROWS_N ${ROWS}u`,
  `#define PWCARD_COLS_N ${COLS}u`,
  "#define PWCARD_DEMO_COL 2u   /* column C */",
  "#define PWCARD_DEMO_LEN 8u",
  "",
  "extern const char PWCARD_ROWS[PWCARD_ROWS_N][PWCARD_COLS_N + 1u];",
  "",
].join("\n"));
writeFileSync(resolve(MAIN, "pwcard_card.c"), [
  "// GENERATED by tools/pwcard/gen_assets.mjs - do not edit.",
  '#include "pwcard_card.h"',
  "",
  `const char PWCARD_ROWS[PWCARD_ROWS_N][PWCARD_COLS_N + 1u] = {`,
  ...card.map((row) => `    "${row}",`),
  "};",
  "",
].join("\n"));
console.log("gen ok: pw_font_22.c (%d glyphs), demo card %dx%d", charset.length, ROWS, COLS);
