// Full 0-9: summaries print row numbers and lengths 4-12 ("12位" needs 2).
const SAMPLES = ["0123456789", "3行C列8位", "1/4", "AJ", "87%"];

// Named UI strings: emitted as readable #define STR_XXX "...".
