// tools/pwcard/gen_assets.mjs - deterministic asset generator for the password
// card prototype: 22px WenKai UI subset (from pwcard_strings.h literal set,
// audited - a missing glyph fails the run) and the fixed demo card derived
// from a 128-bit demo seed via xoshiro128** over a 54-char unambiguous
// alphabet. Requires node >= 18 plus lv_font_conv 1.5.x (--lvfc path to
// lv_font_conv.js). Symbols are passed via this node process, never cmd.exe.
import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const MAIN = resolve(HERE, "../../main");
const args = process.argv.slice(2);
const flag = (name) => (args.includes(name) ? args[args.indexOf(name) + 1] : undefined);
const ttf = flag("--font") || "D:/claude/otp-publish-v13/fonts/LXGWWenKai-Regular.ttf";
const lvfc = flag("--lvfc") || "D:/claude/idiom-staging/node_modules/lv_font_conv/lv_font_conv.js";

// Format-string samples: runtime-formatted ASCII (digits, letters, step
