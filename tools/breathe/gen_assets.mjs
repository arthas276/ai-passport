// tools/breathe/gen_assets.mjs - deterministic asset generator for BREATHE:
// 20px WenKai UI subset (from the STRINGS literal table below, audited - a
// missing glyph fails the run). Requires node >= 18 plus lv_font_conv 1.5.x
// (--lvfc path to lv_font_conv.js). Symbols are passed via this node
// process, never cmd.exe. Same pipeline as tools/tuner/gen_assets.mjs.
import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const MAIN = resolve(HERE, "../../main");
const args = process.argv.slice(2);
const flag = (name) => (args.includes(name) ? args[args.indexOf(name) + 1] : undefined);
const ttf = flag("--font") || "D:/claude/otp-publish-v13/fonts/LXGWWenKai-Regular.ttf";
const lvfc = flag("--lvfc") || "D:/claude/idiom-staging/node_modules/lv_font_conv/lv_font_conv.js";

// Runtime-composed ASCII (set_text_fmt values: durations, minutes, counts,
// pace decimals) must be seeded explicitly - the glyph audit only covers
// literal strings, and a missing digit renders as a tofu box on device.
const SAMPLES = ["0123456789", ".", " ", "%", "/", "·"];

// Named UI strings: emitted as readable #define STR_XXX "..." and shared
// with breath_ui.c (mode names, screen titles, hint pills, units).
const STRINGS = [
  // HOME modes (primary row text)
  ["STR_MODE_FLOW", "相干呼吸"],
  ["STR_MODE_CALM", "放松呼吸"],
  ["STR_MODE_SIGH", "生理叹息"],
  ["STR_MODE_BOX", "箱式呼吸"],
  ["STR_MODE_SLEEP", "睡前放缓"],
  ["STR_MODE_WAKE", "晨间唤醒"],
  ["STR_MODE_YOURS", "我的节奏"],
  // SETUP + rows
  ["STR_SETUP", "设置"],
  ["STR_SET_DUR", "时长"],
  ["STR_SET_GLOW", "夜屏"],
  ["STR_SET_VOL", "音量"],
  ["STR_SET_STATS", "总览"],
  // setting values
  ["STR_DUR_FREE", "不限"],
  ["STR_GLOW_BRIGHT", "常亮"],
  ["STR_GLOW_NIGHT", "夜光"],
  ["STR_GLOW_DARK", "熄屏"],
  // YOURS editor
  ["STR_EDIT_IN", "吸气"],
  ["STR_EDIT_HOLD", "屏息"],
  ["STR_EDIT_OUT", "呼气"],
  ["STR_EDIT_HOLD2", "呼后屏息"],
  ["STR_UNIT_SEC", "秒"],
  // session screen
  ["STR_PHASE_READY", "准备"],
  ["STR_PHASE_TOPUP", "补吸"],
  ["STR_SESSION_END", "长按OK 结束"],
  ["STR_SESSION_CYC", "轮"],
  // summary
  ["STR_SUM_TITLE", "练完了"],
  ["STR_SUM_CYC_UNIT", "轮呼吸"],
  ["STR_SUM_PACE", "节奏"],
  ["STR_SUM_TOTAL", "累计"],
  ["STR_SUM_SESSIONS", "共"],
  ["STR_SUM_MILESTONE", "里程碑"],
  ["STR_UNIT_MIN", "分钟"],
  ["STR_UNIT_TIMES", "次"],
  // hint pills
  ["STR_HINT_SET", "OK 选择 长按OK 返回"],
  ["STR_HINT_EDIT", "上下 调秒 OK 下一步"],
  ["STR_HINT_SAVE", "OK 保存 长按 取消"],
  ["STR_HINT_VOL", "上下 调节 OK 返回"],
  ["STR_HINT_OKHOME", "OK 回主页"],
  ["STR_HINT_BACK", "OK 返回"],
  // stats screen
  ["STR_STATS_LAST", "上次"],
  ["STR_STATS_EMPTY", "还没练过"],
  ["STR_STATS_TOTAL", "共"],
];
const charset = [...new Set(STRINGS.join("") + SAMPLES.join(""))].filter((c) => c !== "\n").join("");
if (charset.includes('"') || charset.includes("\\")) process.exit(2);

mkdirSync(MAIN, { recursive: true });
writeFileSync(resolve(MAIN, "breath_strings.h"), [
  "// GENERATED by tools/breathe/gen_assets.mjs - do not edit.",
  "// Also the glyph-audit source for breath_font_20.c.",
  "#pragma once",
  "",
  ...STRINGS.map(([name, text]) => `#define ${name} ${JSON.stringify(text)}`),
  "",
].join("\n"));

const r = spawnSync(process.execPath, [
  lvfc, "--size", "20", "--bpp", "4", "--no-compress",
  "--format", "lvgl", "--font", ttf,
  "--symbols", charset,
  "--lv-font-name", "breath_font_20",
  "--lv-include", "lvgl.h",
  "-o", resolve(MAIN, "breath_font_20.c"),
]);
if (r.status !== 0) {
  console.error(r.stdout ? r.stdout.toString() : "", r.stderr ? r.stderr.toString() : "");
  process.exit(r.status ?? 1);
}
const fontC = readFileSync(resolve(MAIN, "breath_font_20.c"), "utf8");
const missing = [...charset].filter((c) => c !== " " && !fontC.includes(c));
if (missing.length) {
  console.error("glyph audit FAILED, missing:", missing.join(" "));
  process.exit(3);
}
console.log(`gen ok: breath_font_20.c (${charset.length} glyphs)`);
