// tools/tuner/gen_assets.mjs - deterministic asset generator for TUNER:
// 20px WenKai UI subset (from the STRINGS literal table below, audited - a
// missing glyph fails the run). Requires node >= 18 plus lv_font_conv 1.5.x
// (--lvfc path to lv_font_conv.js). Symbols are passed via this node
// process, never cmd.exe.
import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const MAIN = resolve(HERE, "../../main");
const args = process.argv.slice(2);
const flag = (name) => (args.includes(name) ? args[args.indexOf(name) + 1] : undefined);
const ttf = flag("--font") || "D:/claude/otp-publish-v13/fonts/LXGWWenKai-Regular.ttf";
const lvfc = flag("--lvfc") || "D:/claude/idiom-staging/node_modules/lv_font_conv/lv_font_conv.js";

// Format-string samples: runtime-formatted ASCII (string numbers, note
// names in the voice range, A4/volume values) must be seeded explicitly -
// the glyph audit only covers literal strings, and a missing digit renders
// as a tofu box on device.
const SAMPLES = ["0123456789", "/", "-", "Hz", "A4", "ABCDEFG#", "OK", " "];

// Named UI strings: emitted as readable #define STR_XXX "..." and shared
// with tuner_modes.c (mode names) and tuner_ui.c (labels, hints, settings).
const STRINGS = [
  ["STR_MODE_CHROMATIC", "自由"],
  ["STR_MODE_GUITAR", "吉他"],
  ["STR_MODE_UKULELE", "尤克里里"],
  ["STR_MODE_VIOLIN", "小提琴"],
  ["STR_MODE_VOICE", "人声"],
  ["STR_STATUS_LOW", "偏低"],
  ["STR_STATUS_HIGH", "偏高"],
  ["STR_STATUS_INTUNE", "准了"],
  ["STR_STATUS_ALLDONE", "全弦调准"],
  ["STR_AUX_STR", "弦"],
  ["STR_AUX_RANGE", "音域"],
  ["STR_HINT_FROZEN", "已暂停 OK 继续"],
  ["STR_HINT_REF", "上下选弦 长按上 参考音"],
  ["STR_HINT_BASIC", "OK 暂停 长按OK 模式"],
  ["STR_HINT_SET", "长按下 设置"],
  ["STR_SET_TITLE", "设置"],
  ["STR_SET_A4", "A4 基准"],
  ["STR_SET_TP", "移调"],
  ["STR_SET_VOL", "音量"],
  ["STR_TP_OFF", "关"],
  ["STR_TP_BB", "降B"],
  ["STR_TP_EB", "降E"],
  ["STR_TP_F", "F"],
  ["STR_SET_FOOT", "OK 调整 · 长按OK 保存"],
];
const charset = [...new Set(STRINGS.join("") + SAMPLES.join(""))].filter((c) => c !== "\n").join("");
if (charset.includes('"') || charset.includes("\\")) process.exit(2);

mkdirSync(MAIN, { recursive: true });
writeFileSync(resolve(MAIN, "tuner_strings.h"), [
  "// GENERATED by tools/tuner/gen_assets.mjs - do not edit.",
  "// Also the glyph-audit source for tuner_font_20.c.",
  "#pragma once",
  "",
  ...STRINGS.map(([name, text]) => `#define ${name} ${JSON.stringify(text)}`),
  "",
].join("\n"));

const r = spawnSync(process.execPath, [
  lvfc, "--size", "20", "--bpp", "4", "--no-compress",
  "--format", "lvgl", "--font", ttf,
  "--symbols", charset,
  "--lv-font-name", "tuner_font_20",
  "--lv-include", "lvgl.h",
  "-o", resolve(MAIN, "tuner_font_20.c"),
]);
if (r.status !== 0) {
  console.error(r.stdout ? r.stdout.toString() : "", r.stderr ? r.stderr.toString() : "");
  process.exit(r.status ?? 1);
}
const fontC = readFileSync(resolve(MAIN, "tuner_font_20.c"), "utf8");
const missing = [...charset].filter((c) => c !== " " && !fontC.includes(c));
if (missing.length) {
  console.error("glyph audit FAILED, missing:", missing.join(" "));
  process.exit(3);
}
console.log(`gen ok: tuner_font_20.c (${charset.length} glyphs)`);
