// tools/idiom/gen_assets.mjs - deterministic asset generator for the idiom app.
//
// Inputs : tools/idiom/wordlist.txt  (one 4-character idiom per line, UTF-8)
//          main/idiom_strings.h      (UI literals; feeds the 22 px subset)
//          TTF (default D:/claude/otp-publish-v13/fonts/LXGWWenKai-Regular.ttf,
//          override with --font)
// Outputs: main/idiom_words.c/.h     (codepoint + UTF-8 tables)
//          main/idiom_font_32.c/.h   (LXGW WenKai 32 px 4 bpp subset:
//              wordlist characters + STR_BIG_* big-type words)
//          main/idiom_font_22.c/.h   (22 px 4 bpp subset: every literal in
//              idiom_strings.h + digits + " %/-·▲▼.")
//
// Requires node >= 18 and the lv_font_conv CLI:  npm i -g lv_font_conv@1.5.3
// (or set LVFC to the lv_font_conv.js path). Symbols are passed as a UTF-8
// file argument list via this node process (never through cmd.exe), so the
// Windows codepage cannot mangle the CJK command line.
//
// The script audits its own output: it fails if any required codepoint is
// missing from a generated font, if the wordlist has a wrong-length or
// duplicate entry, or if a glyph renders outside its em box metrics.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, "..", "..");
const mainDir = join(repo, "main");
const args = process.argv.slice(2);
const flag = (name) => (args.includes(name) ? args[args.indexOf(name) + 1] : undefined);
const fontArg = flag("--font") || "D:/claude/otp-publish-v13/fonts/LXGWWenKai-Regular.ttf";

function fail(msg) { console.error("gen_assets: FAIL - " + msg); process.exit(1); }

// ---- wordlist -> idiom_words.c/h -------------------------------------------
const wordlist = readFileSync(join(here, "wordlist.txt"), "utf8")
    .split(/\r?\n/).map(s => s.trim()).filter(Boolean);
if (wordlist.length === 0) fail("empty wordlist");
const seen = new Set();
for (const w of wordlist) {
    const cps = [...w];
    if (cps.length !== 4) fail(`"${w}" has ${cps.length} characters (need 4)`);
    if (seen.has(w)) fail(`duplicate idiom "${w}"`);
    seen.add(w);
}

const wordsH = `// GENERATED by tools/idiom/gen_assets.mjs - do not edit.
#pragma once
#include <stdint.h>
#define IDIOM_COUNT ${wordlist.length}u
extern const uint32_t IDIOM_WORDS_CP[IDIOM_COUNT][4];
extern const char IDIOM_WORDS_UTF8[IDIOM_COUNT][13];
const char *idiom_word_utf8(uint16_t idx);
`;
const rowsCp = wordlist.map(w => "    {" + [...w].map(c => "0x" + c.codePointAt(0).toString(16).toUpperCase().padStart(4, "0")).join(", ") + "}").join(",\n");
const rowsUtf = wordlist.map(w => `    "${w}"`).join(",\n");
const wordsC = `// GENERATED by tools/idiom/gen_assets.mjs - do not edit.
#include "idiom_words.h"
const uint32_t IDIOM_WORDS_CP[IDIOM_COUNT][4] = {
${rowsCp},
};
const char IDIOM_WORDS_UTF8[IDIOM_COUNT][13] = {
${rowsUtf},
};
const char *idiom_word_utf8(uint16_t idx) {
    return idx < IDIOM_COUNT ? IDIOM_WORDS_UTF8[idx] : "";
}
`;
writeFileSync(join(mainDir, "idiom_words.h"), wordsH);
writeFileSync(join(mainDir, "idiom_words.c"), wordsC);

// ---- string literals -> symbol sets ---------------------------------------
const stringsH = readFileSync(join(mainDir, "idiom_strings.h"), "utf8");
const literals = [...stringsH.matchAll(/"([^"]*)"/g)].map(m => m[1]);
const allLit = literals.join("");

const wordChars = [...new Set(wordlist.join(""))].sort();
const bigWords = ["成语翻牌猜中了没猜中战绩怎么玩"];
const font32Set = [...new Set(wordChars.join("") + bigWords.join(""))].sort();
const asciiExtra = " 0123456789%/-·▲▼.";
const font22Set = [...new Set(allLit + asciiExtra)].sort().filter(c => c !== "\n");

// ---- run lv_font_conv ------------------------------------------------------
const lvfc = flag("--lvfc") || process.env.LVFC || "lv_font_conv";
function genFont(size, symbols, out) {
    const symFile = join(here, `symbols_${size}.txt`);
    writeFileSync(symFile, symbols.join(""));
    const r = spawnSync(process.execPath, [
        lvfc.endsWith(".js") ? lvfc : lvfc,
        "--size", String(size), "--bpp", "4", "--no-compress",
        "--format", "lvgl", "--font", fontArg,
        "--symbols", readFileSync(symFile, "utf8"),
        "-o", out,
    ], { stdio: ["ignore", "inherit", "inherit"], shell: false });
    if (r.status !== 0) fail(`lv_font_conv ${size}px exited ${r.status}`);
    // ESP-IDF's LVGL component exposes "lvgl.h" (OTP/SLANG fonts do the
    // same); 1.5.3 emits "lvgl/lvgl.h" in the #else branch - rewrite it.
    let body = readFileSync(out, "utf8");
    body = body.replaceAll('#include "lvgl/lvgl.h"', '#include "lvgl.h"');
    writeFileSync(out, body);
}
const f32 = join(mainDir, "idiom_font_32.c");
const f22 = join(mainDir, "idiom_font_22.c");
genFont(32, font32Set, f32);
genFont(22, font22Set, f22);

// ---- audit -----------------------------------------------------------------
for (const [file, set] of [[f32, font32Set], [f22, font22Set]]) {
    const body = readFileSync(file, "utf8");
    const have = new Set([...body.matchAll(/U\+([0-9A-F]{4,})/g)].map(m => parseInt(m[1], 16)));
    const missing = set.filter(c => !have.has(c.codePointAt(0)));
    if (missing.length) fail(`${file} missing glyphs: ${missing.join(" ")}`);
}
const kb = f => (readFileSync(f).length / 1024).toFixed(1);
console.log(`gen_assets: OK - ${wordlist.length} idioms, ${wordChars.length} word chars,`);
console.log(`  font32 ${font32Set.length} glyphs -> ${kb(f32)} KB source`);
console.log(`  font22 ${font22Set.length} glyphs -> ${kb(f22)} KB source`);
console.log(`  coverage audit: every required codepoint present`);
